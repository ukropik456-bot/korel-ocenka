# ── СТИЛИ ────────────────────────────────────────────────────────────────
ST_TITLE = ParagraphStyle(
    'Title', fontName='ArialBd', fontSize=16, leading=20,
    alignment=TA_CENTER, spaceAfter=4*mm, textColor='#190F23',
)
ST_SUBTITLE = ParagraphStyle(
    'Subtitle', fontName='Arial', fontSize=11, leading=14,
    alignment=TA_CENTER, spaceAfter=10*mm, textColor='#666',
)
ST_H = ParagraphStyle(
    'H', fontName='ArialBd', fontSize=11, leading=14,
    spaceBefore=6*mm, spaceAfter=2*mm, textColor='#190F23',
)
ST_P = ParagraphStyle(
    'P', fontName='Arial', fontSize=10, leading=14,
    alignment=TA_JUSTIFY, spaceAfter=2*mm, firstLineIndent=8*mm,
)
ST_LI = ParagraphStyle(
    'LI', fontName='Arial', fontSize=10, leading=14,
    alignment=TA_JUSTIFY, spaceAfter=1*mm, leftIndent=12*mm,
    bulletIndent=8*mm,
)
ST_FOOT = ParagraphStyle(
    'Foot', fontName='ArialIt', fontSize=9, leading=12,
    alignment=TA_CENTER, textColor='#888', spaceBefore=6*mm,
)

def H(text):  return Paragraph(text, ST_H)
def P(text):  return Paragraph(text, ST_P)
def LI(text): return Paragraph('— ' + text, ST_LI)
def SP(h=2):  return Spacer(1, h*mm)

